"""Generate docs/MCP_TOOLS.md from the live tool registry, so the reference
always matches the server.  Run:  .venv/bin/python -m pdfeditor.agent.gen_docs
"""
from __future__ import annotations

import inspect
import os

from .server import mcp

OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.dirname(
    os.path.abspath(__file__)))), "docs", "MCP_TOOLS.md")

GROUPS = [
    ("Documents", ["open_pdf", "list_open_pdfs", "get_document_info", "save_pdf",
                   "close_pdf", "undo", "redo"]),
    ("Seeing the document", ["render_page", "get_page_layout", "get_text", "find_text"]),
    ("Deleting content", ["delete_elements", "delete_region"]),
    ("Text", ["edit_text", "replace_text", "add_text", "add_html_text"]),
    ("Graphics & annotations", ["add_image", "add_shape", "add_annotation"]),
    ("Re-layout", ["move_elements", "move_region"]),
    ("Forms", ["list_form_fields", "fill_form", "add_form_field", "update_form_field",
               "delete_form_field", "flatten_form"]),
    ("Pages", ["delete_pages", "reorder_pages", "move_page", "insert_blank_page",
               "duplicate_page", "rotate_pages", "insert_pages_from_pdf", "crop_page",
               "extract_pages"]),
    ("Live viewer", ["open_in_viewer"]),
]


def _type(schema: dict) -> str:
    if "anyOf" in schema:
        parts = [_type(s) for s in schema["anyOf"] if s.get("type") != "null"]
        return " \\| ".join(parts) or "any"
    if "enum" in schema:
        return " \\| ".join(f"`{v}`" for v in schema["enum"])
    t = schema.get("type", "any")
    if t == "array":
        return f"list of {_type(schema.get('items', {}))}"
    return {"integer": "int", "number": "number", "string": "string",
            "boolean": "bool", "object": "object"}.get(t, t)


def render() -> str:
    tools = {t.name: t for t in mcp._tool_manager.list_tools()}
    lines = [
        "# Quill MCP tool reference",
        "",
        "<!-- Generated by `python -m pdfeditor.agent.gen_docs` — do not edit by hand. -->",
        "",
        "All tools return compact JSON (`render_page` also returns a PNG). Pages are",
        "numbered from 1; rects are `[x0, y0, x1, y1]` in PDF points, origin top-left.",
        "Every tool accepts an optional `doc` (the handle returned by `open_pdf`) and",
        "defaults to the most recently opened PDF. Errors come back as tool errors",
        "with a plain-language explanation.",
        "",
    ]
    listed = set()
    for title, names in GROUPS:
        lines += [f"## {title}", ""]
        for name in names:
            t = tools[name]
            listed.add(name)
            desc = inspect.cleandoc(t.description or "").replace("<", "&lt;").replace(">", "&gt;")
            lines += [f"### `{name}`", "", desc, ""]
            props = t.parameters.get("properties", {})
            required = set(t.parameters.get("required", []))
            rows = [(p, s) for p, s in props.items() if p != "doc"]
            if rows:
                lines += ["| Parameter | Type | Default |", "| --- | --- | --- |"]
                for p, s in rows:
                    default = "*required*" if p in required else f"`{s.get('default')!r}`"
                    lines.append(f"| `{p}` | {_type(s)} | {default} |")
                lines.append("")
    missing = sorted(set(tools) - listed)
    if missing:
        raise SystemExit(f"Tools missing from GROUPS: {missing}")
    return "\n".join(lines).rstrip() + "\n"


if __name__ == "__main__":
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as fh:
        fh.write(render())
    print(f"wrote {OUT}")
